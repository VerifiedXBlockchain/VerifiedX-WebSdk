import KeypairService, { hkdfSha256 } from '../services/keypair-service';
import { Network } from '../constants';
import { VfxClient } from '../index';
import { installFetch } from './helpers/mock-fetch';
import flowVectors from './compat/wallet-flow-vectors.json';

/** A Spyglass older than the activity route: findLegacyRecovery falls back to the history reads. */
const olderSpyglass = {
  '/addresses/activity/': () => new Response('{"detail":"Not found."}', { status: 404 }),
};

const testnet = new KeypairService(Network.Testnet);
const mainnet = new KeypairService(Network.Mainnet);
const hex = (bytes: Uint8Array) => Buffer.from(bytes).toString('hex');
const fromHex = (text: string) => Uint8Array.from(Buffer.from(text, 'hex'));

describe('hkdfSha256', () => {
  test('matches RFC 5869 test cases 1 and 3', () => {
    const okm1 = hkdfSha256(
      fromHex('0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b'),
      fromHex('000102030405060708090a0b0c'),
      fromHex('f0f1f2f3f4f5f6f7f8f9'),
      42,
    );
    expect(hex(okm1)).toBe('3cb25f25faacd57a90434f64d0362f2a2d2d0a90cf1a5a4c5db02d56ecc4c5bf34007208d5b887185865');
    const okm3 = hkdfSha256(
      fromHex('0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b0b'),
      new Uint8Array(0),
      new Uint8Array(0),
      42,
    );
    expect(hex(okm3)).toBe('8da4e775a563c18f715f802a063c5a31b8a11f5c5ee1879ec3454e5f3c738d2d9d201395faa4b61a96c8');
  });
});

describe('recoveryKeyFromPasskeyPrf', () => {
  const prf = fromHex('7f'.repeat(32));

  test('is deterministic, an ordinary account, and not the PRF output itself', () => {
    const key = testnet.recoveryKeyFromPasskeyPrf(prf);
    expect(testnet.recoveryKeyFromPasskeyPrf(prf.buffer.slice(0) as ArrayBuffer)).toEqual(key);
    expect(key.privateKey).toMatch(/^00[0-9a-f]{64}$/);
    expect(key.privateKey.slice(2)).not.toBe(hex(prf));
    expect(key.address).toBe(testnet.addressFromPrivate(key.privateKey));
    expect(key.address.startsWith('xRBX')).toBe(false);
    expect(mainnet.recoveryKeyFromPasskeyPrf(prf).privateKey).toBe(key.privateKey);
  });

  // Pinned so the salt, info or HKDF can never change silently: a change
  // would lock every passkey-recovered vault out of its recovery key.
  test('pins the derivation', () => {
    expect(testnet.recoveryKeyFromPasskeyPrf(prf).privateKey).toBe(PINNED_PRF_KEY);
  });

  test('different PRF outputs give different keys, and short outputs are refused', () => {
    expect(testnet.recoveryKeyFromPasskeyPrf(fromHex('01'.repeat(32))).privateKey).not.toBe(
      testnet.recoveryKeyFromPasskeyPrf(prf).privateKey,
    );
    expect(() => testnet.recoveryKeyFromPasskeyPrf(new Uint8Array(16))).toThrow(/at least 32 bytes/);
  });
});

describe('newRecoveryKey and newVaultKeypair', () => {
  test('are random, independent keys', () => {
    const vault = testnet.newVaultKeypair();
    const recovery = testnet.newRecoveryKey();
    expect(vault.address.startsWith('xRBX')).toBe(true);
    expect(recovery.address.startsWith('xRBX')).toBe(false);
    expect(recovery.privateKey).not.toBe(vault.privateKey);
    // Nothing about the recovery key is computable from the vault key.
    expect(testnet.restoreLegacyWebWalletVaultFromVaultKey(vault.privateKey).recoveryAddress).not.toBe(
      recovery.address,
    );
    expect(testnet.newRecoveryKey().privateKey).not.toBe(recovery.privateKey);
  });
});

// Node's crypto.hkdfSync('sha256', 0x7f x 32, salt, info, 32) gives the same 32 bytes.
const PINNED_PRF_KEY = '00ab4d4b9d0c37c1bb2f30e93094078ebe77473587661270e6e662de7e02b34c46';

describe('legacy recovery (Flutter web wallet vaults)', () => {
  // From wallet-flow-vectors.json, generated by running the Flutter wallet's
  // own Dart and keygen-v3.js: email test@verifiedx.io / test1234.
  const walletVector = flowVectors.email[0];

  test('deriveLegacyRecoveryKey matches the Flutter wallet from the main key, the vault key and the text', () => {
    for (const [network, service] of [
      ['testnet', testnet],
      ['mainnet', mainnet],
    ] as const) {
      const expected = walletVector[network].reserve;
      const fromMain = service.deriveLegacyRecoveryKey({ mainPrivateKey: '00' + walletVector.privateKey });
      expect(fromMain).toEqual({
        privateKey: '00' + expected.recoveryPrivateKey,
        publicKey: expected.recoveryPublicKey,
        address: expected.recoveryAddress,
        vaultAddress: expected.address,
      });
      expect(service.deriveLegacyRecoveryKey({ vaultPrivateKey: expected.privateKey })).toEqual(fromMain);
      expect(service.deriveLegacyRecoveryKey({ derivationText: walletVector.derivationText })).toEqual(fromMain);
    }
  });

  const derived = testnet.deriveLegacyRecoveryKey({ mainPrivateKey: '00' + walletVector.privateKey });
  const empty = { count: 0, page: 1, num_pages: 1, results: [] };
  const details = (address: string, overrides: Record<string, unknown> = {}) => ({
    address,
    balance: 0,
    balance_total: 0,
    balance_locked: 0,
    adnr: null,
    activated: false,
    ...overrides,
  });

  afterEach(() => jest.restoreAllMocks());

  test('no balance, no transactions, no vault record: hasActivity false and no key', async () => {
    const { calls } = installFetch({
      ...olderSpyglass,
      [`/transaction/address/`]: () => empty,
      [`/addresses/${derived.address}`]: () => details(derived.address),
      [`/addresses/${derived.vaultAddress}`]: () => new Response('{"detail":"Not found."}', { status: 404 }),
    });
    const result = await new VfxClient('testnet').findLegacyRecovery({
      mainPrivateKey: '00' + walletVector.privateKey,
    });
    expect(result).toEqual({
      address: derived.address,
      vaultAddress: derived.vaultAddress,
      hasActivity: false,
      summary: {
        recoveryHasBalance: false,
        recoveryHasTransactions: false,
        vaultHasBalance: false,
        vaultHasTransactions: false,
        vaultActivated: false,
        registeredWithThisRecovery: false,
      },
      lookedUpWith: 'history',
    });
    expect(calls.map((c) => c.url.split('/api')[1].split('?')[0]).sort()).toEqual(
      [
        '/addresses/activity/',
        `/addresses/${derived.address}`,
        `/addresses/${derived.vaultAddress}`,
        `/transaction/address/${derived.address}/`,
        `/transaction/address/${derived.vaultAddress}/`,
      ].sort(),
    );
  });

  test('a Register() from the vault naming the recovery address: hasActivity true, key on request', async () => {
    installFetch({
      ...olderSpyglass,
      [`/transaction/address/${derived.address}/`]: () => empty,
      [`/transaction/address/${derived.vaultAddress}/`]: () => ({
        count: 1,
        page: 1,
        num_pages: 1,
        results: [
          {
            hash: 'h',
            to_address: 'Reserve_Base',
            from_address: derived.vaultAddress,
            data: JSON.stringify({ Function: 'Register()', RecoveryAddress: derived.address }),
          },
        ],
      }),
      [`/addresses/${derived.address}`]: () => details(derived.address),
      [`/addresses/${derived.vaultAddress}`]: () => details(derived.vaultAddress, { activated: true, balance: '1.5' }),
    });
    const client = new VfxClient('testnet');
    const result = await client.findLegacyRecovery(
      { mainPrivateKey: '00' + walletVector.privateKey },
      { includeKey: true },
    );
    expect(result.hasActivity).toBe(true);
    expect(result.summary).toMatchObject({
      vaultActivated: true,
      registeredWithThisRecovery: true,
      vaultHasBalance: true,
      vaultHasTransactions: true,
    });
    expect(result.recoveryKey).toEqual({
      privateKey: derived.privateKey,
      publicKey: derived.publicKey,
      address: derived.address,
    });
  });

  test('only a balance on the recovery address still counts', async () => {
    installFetch({
      ...olderSpyglass,
      [`/transaction/address/`]: () => empty,
      [`/addresses/${derived.address}`]: () => details(derived.address, { balance_total: '0.25' }),
      [`/addresses/${derived.vaultAddress}`]: () => details(derived.vaultAddress),
    });
    const result = await new VfxClient('testnet').findLegacyRecovery({
      vaultPrivateKey: walletVector.testnet.reserve.privateKey,
    });
    expect(result.hasActivity).toBe(true);
    expect(result.summary.recoveryHasBalance).toBe(true);
    expect(result).not.toHaveProperty('recoveryKey');
  });

  test('a Spyglass outage throws instead of reading as "no activity"', async () => {
    installFetch({
      ...olderSpyglass,
      [`/transaction/address/`]: () => new Response('down', { status: 502 }),
      [`/addresses/`]: () => details(derived.address),
    });
    await expect(
      new VfxClient('testnet').findLegacyRecovery({ mainPrivateKey: '00' + walletVector.privateKey }),
    ).rejects.toMatchObject({ name: 'VfxApiError' });
  });
});

describe('findLegacyRecovery reads the whole vault history', () => {
  const walletVector = flowVectors.email[0];
  const derived = testnet.deriveLegacyRecoveryKey({ mainPrivateKey: '00' + walletVector.privateKey });

  afterEach(() => jest.restoreAllMocks());

  test('finds a Register() that sits past the first page', async () => {
    const send = { hash: 's', to_address: 'xSomeone', from_address: derived.vaultAddress, data: null };
    const register = {
      hash: 'r',
      to_address: 'Reserve_Base',
      from_address: derived.vaultAddress,
      data: JSON.stringify({ Function: 'Register()', RecoveryAddress: derived.address }),
    };
    const { calls } = installFetch({
      ...olderSpyglass,
      [`/transaction/address/${derived.address}/`]: () => ({ count: 0, page: 1, num_pages: 1, results: [] }),
      [`/transaction/address/${derived.vaultAddress}/`]: (url) =>
        new URL(url).searchParams.get('page') === '3'
          ? { count: 101, page: 3, num_pages: 3, results: [register] }
          : { count: 101, page: 1, num_pages: 3, results: Array(50).fill(send) },
      [`/addresses/`]: () => ({ address: 'x', balance: 0, balance_total: 0, activated: true }),
    });
    const result = await new VfxClient('testnet').findLegacyRecovery({
      mainPrivateKey: '00' + walletVector.privateKey,
    });
    expect(result.summary.registeredWithThisRecovery).toBe(true);
    const pages = calls
      .filter((c) => c.url.includes(`/transaction/address/${derived.vaultAddress}/`))
      .map((c) => new URL(c.url).searchParams.get('page'));
    expect(pages).toEqual(['1', '2', '3']);
  });
});

